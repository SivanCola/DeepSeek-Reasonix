#!/usr/bin/env node

import fs from "node:fs";

const [version, checksumsPath, outputPath] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version || "") || !checksumsPath || !outputPath) {
  throw new Error("usage: render-homebrew-cask.mjs X.Y.Z SHA256SUMS OUTPUT");
}

const required = [
  "reasonix-darwin-amd64.tar.gz",
  "reasonix-darwin-arm64.tar.gz",
  "reasonix-linux-amd64.tar.gz",
  "reasonix-linux-arm64.tar.gz",
];
const sums = new Map();
for (const line of fs.readFileSync(checksumsPath, "utf8").trim().split(/\r?\n/)) {
  const match = line.match(/^([0-9a-f]{64})  (\S+)$/);
  if (!match) throw new Error(`invalid SHA256SUMS line: ${line}`);
  if (sums.has(match[2])) throw new Error(`duplicate checksum entry: ${match[2]}`);
  sums.set(match[2], match[1]);
}
for (const name of required) {
  if (!sums.has(name)) throw new Error(`missing checksum entry: ${name}`);
}

const sha = (name) => sums.get(name);
const content = `# This file was generated by GoReleaser. DO NOT EDIT.
cask "reasonix" do
  version "${version}"

  on_macos do
    on_intel do
      sha256 "${sha("reasonix-darwin-amd64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-darwin-amd64.tar.gz"
    end
    on_arm do
      sha256 "${sha("reasonix-darwin-arm64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-darwin-arm64.tar.gz"
    end
  end

  on_linux do
    on_intel do
      sha256 "${sha("reasonix-linux-amd64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-linux-amd64.tar.gz"
    end
    on_arm do
      sha256 "${sha("reasonix-linux-arm64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-linux-arm64.tar.gz"
    end
  end

  name "reasonix"
  desc "Cache-first DeepSeek coding agent for the terminal."
  homepage "https://github.com/esengine/DeepSeek-Reasonix"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "reasonix"

  postflight do
    if OS.mac?
      system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{staged_path}/reasonix"]
    end
  end

  # No zap stanza required

end
`;

fs.writeFileSync(outputPath, content);
